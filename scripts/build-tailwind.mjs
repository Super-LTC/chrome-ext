#!/usr/bin/env node
/**
 * Compile Tailwind, then SCOPE every selector under `.sltc-tw`.
 *
 * ── Why scoping and not a prefix ────────────────────────────────────────────
 *
 * The plan called for "prefix AND root scope". A prefix is wrong HERE, and the
 * reason is the whole point of adding Tailwind at all: we want the web's
 * components to port by copy-paste, and they carry ~1,057 stock class strings
 * (`className="flex text-sm text-slate-500"`). Turning on a prefix means
 * rewriting every one of them to `tw:flex tw:text-sm …` — which is exactly the
 * hand-translation cost, and the recurring drift, that Tailwind was adopted to
 * avoid. So: no prefix.
 *
 * Root-scoping alone covers the risk a prefix was meant to cover:
 *
 *   Bleed OUT (our utilities restyling PointClickCare) — impossible. Every
 *   selector is rewritten to sit under `.sltc-tw`, which only ever appears on
 *   containers we render.
 *
 *   Bleed IN (PCC's CSS hitting our elements) — a prefix would dodge a name
 *   collision like PCC defining its own `.flex`. Scoping handles it a different
 *   way: `.sltc-tw .flex` is specificity (0,2,0) against PCC's (0,1,0), so ours
 *   wins any property we set. The residual case is a PCC rule setting a property
 *   our utility does NOT set (their `.flex { margin: 10px }` vs our
 *   `display:flex`) — which Tailwind's preflight, also scoped here, resets for us.
 *
 * ── Why a build step rather than a postcss.config.js ────────────────────────
 *
 * A root postcss config applies to EVERY stylesheet Vite processes, and the
 * scoping plugin would then rewrite all ~40 hand-written BEM files too, breaking
 * every existing screen. Compiling one file explicitly keeps the transform where
 * it belongs. The output is a normal file on disk, so it also stays greppable and
 * diffable when a utility does something unexpected.
 *
 * Wired into the build as a Vite plugin (see vite.config.js) so it re-runs on
 * every build and every watch rebuild.
 */
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';
import prefixSelector from 'postcss-prefix-selector';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

export const SCOPE = '.sltc-tw';
/** Prefix for @keyframes names — see `namespaceKeyframes`. */
export const KEYFRAME_PREFIX = 'sltc-';
const SRC = path.join(ROOT, 'content/css/tailwind.src.css');
const OUT = path.join(ROOT, 'content/css/tailwind.generated.css');

const BANNER = `/* GENERATED by scripts/build-tailwind.mjs — do not edit.
 * Tailwind, compiled and scoped under ${SCOPE}. Source: content/css/tailwind.src.css
 */\n`;

/**
 * Namespace `@keyframes` names, because selector scoping cannot reach them.
 *
 * An animation NAME is global no matter which selector references it. Tailwind
 * emits `@keyframes pulse` for `animate-pulse`, and `pulse` is about as generic
 * as a name gets — if PointClickCare defines its own, whichever stylesheet loads
 * later silently wins for BOTH of us. Our skeleton would animate like theirs, or,
 * worse in our direction, theirs would animate like ours: a change to the host
 * page, which is precisely what the scoping promise rules out.
 *
 * Every hand-written stylesheet in this repo already namespaces its keyframes
 * (`cpas-spin`, `dx-fade-in`, `cm-slide-up`). This makes the generated CSS follow
 * the same rule, so the output adds no unnamespaced globals at all.
 *
 * Both halves must move together — the at-rule and every `animation` /
 * `animation-name` that references it — or the utility silently stops animating.
 */
function namespaceKeyframes(root) {
  const renamed = new Set();
  root.walkAtRules('keyframes', (rule) => {
    const name = rule.params.trim();
    if (name.startsWith(KEYFRAME_PREFIX)) return;
    rule.params = KEYFRAME_PREFIX + name;
    renamed.add(name);
  });
  if (!renamed.size) return;

  // Word-boundary replace so `pulse` doesn't also rewrite `pulse-fast`.
  const pattern = new RegExp(`\\b(${[...renamed].map((n) => n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})\\b`, 'g');

  /**
   * Rewrite the animation NAME but never a `var(...)` reference.
   *
   * Tailwind v4 indirects animations through theme variables:
   *   --animate-pulse: pulse 2s …;   ← the name lives in the VALUE
   *   animation: var(--animate-pulse);
   *
   * A naive replace over the whole declaration turns the second line into
   * `var(--animate-sltc-pulse)` — a variable nothing defines, so the animation
   * silently stops. (It did exactly that on the first attempt here.) The name
   * has to move inside the definition's value; the reference must not be touched.
   */
  const renameOutsideVar = (value) =>
    value
      .split(/(var\([^)]*\))/g)
      .map((part) => (part.startsWith('var(') ? part : part.replace(pattern, (m) => KEYFRAME_PREFIX + m)))
      .join('');

  root.walkDecls((decl) => {
    const isAnimation = /^(animation|animation-name)$/.test(decl.prop);
    // `--animate-*` is where v4 keeps the shorthand the utility points at.
    const isAnimateVar = decl.prop.startsWith('--animate-');
    if (isAnimation || isAnimateVar) decl.value = renameOutsideVar(decl.value);
  });
}

export async function buildTailwind({ quiet = false } = {}) {
  const css = readFileSync(SRC, 'utf-8');

  const result = await postcss([
    tailwind(),
    prefixSelector({
      prefix: SCOPE,
      transform(prefix, selector, prefixedSelector) {
        // `:root` / `:host` carry Tailwind's theme custom properties. Those must
        // land ON the scope container, not on a descendant of it, or every
        // `var(--color-slate-500)` inside resolves to nothing.
        if (selector === ':root' || selector === ':host' || selector === ':root, :host') {
          return prefix;
        }
        // Preflight's `html` / `body` rules can never match inside our subtree.
        // Retarget them at the container so the resets they carry (font stack,
        // line-height, margin zeroing) still apply to what we render.
        if (/^(html|body)$/.test(selector)) return prefix;
        // `*`, `::before`, `::after` → descendants of the scope. `prefixedSelector`
        // already does the right thing for these and for every plain utility.
        return prefixedSelector;
      },
    }),
  ]).process(css, { from: SRC, to: OUT });

  namespaceKeyframes(result.root);

  mkdirSync(path.dirname(OUT), { recursive: true });
  const out = result.root.toString();
  writeFileSync(OUT, BANNER + out);

  if (!quiet) {
    const kb = (Buffer.byteLength(out) / 1024).toFixed(1);
    console.log(`[tailwind] ${path.relative(ROOT, OUT)} — ${kb} kB`);
  }
  return out;
}

/** Vite plugin: regenerate before each build, and on source/component changes. */
export function tailwindScoped() {
  return {
    name: 'tailwind-scoped',
    enforce: 'pre',
    async buildStart() { await buildTailwind({ quiet: true }); },
  };
}

// Direct invocation: `node scripts/build-tailwind.mjs`
if (import.meta.url === `file://${process.argv[1]}`) {
  await buildTailwind();
}
